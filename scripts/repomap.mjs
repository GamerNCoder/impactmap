#!/usr/bin/env node
// Compact repo map for Go students: routes, files with their exports/imports-from-@, DB tables.
// Deterministic, no LLM. Usage: node scripts/repomap.mjs [root] > map.md   (~2k tokens)
import { readFileSync, readdirSync, statSync } from 'node:fs'
import { join, relative } from 'node:path'

const root = process.argv[2] || process.cwd()
const walk = (d) => readdirSync(d).flatMap((f) => {
  const p = join(d, f)
  return statSync(p).isDirectory() ? walk(p) : [p]
})

const out = ['# ImpactMap repo map (generated by scripts/repomap.mjs)', '',
  'Next.js 16 App Router + React 19 + Tailwind v4 + Supabase (RLS). `@/` = `src/`.', '']

const files = walk(join(root, 'src')).filter((f) => /\.(tsx?|mjs)$/.test(f)).sort()
const pages = [], apis = [], libs = []
for (const f of files) {
  const rel = relative(root, f)
  const src = readFileSync(f, 'utf8')
  const exp = [...src.matchAll(/export\s+(?:default\s+)?(?:async\s+)?(?:function|const|class|type|interface)\s+(\w+)/g)].map((m) => m[1])
  const deps = [...new Set([...src.matchAll(/from '@\/([^']+)'/g)].map((m) => m[1]))]
  const client = /^['"]use client['"]/.test(src.trimStart()) ? ' (client)' : ''
  const line = `${rel}${client}: ${exp.join(', ') || '-'}${deps.length ? `  <- ${deps.join(', ')}` : ''}`
  if (/\/route\.ts$/.test(rel)) {
    const methods = [...src.matchAll(/export\s+async\s+function\s+(GET|POST|PUT|PATCH|DELETE)/g)].map((m) => m[1])
    apis.push(`${rel.replace(/^src\/app/, '').replace(/\/route\.ts$/, '')} [${methods.join(',')}]  ${rel}${deps.length ? `  <- ${deps.join(', ')}` : ''}`)
  } else if (/\/page\.tsx$/.test(rel)) {
    pages.push(`${rel.replace(/^src\/app/, '').replace(/\/page\.tsx$/, '') || '/'}  ${rel}${deps.length ? `  <- ${deps.join(', ')}` : ''}`)
  } else libs.push(line)
}
out.push('## Pages', ...pages, '', '## API routes', ...apis, '', '## Components / lib (exports  <- @/ imports)', ...libs, '')

const migDir = join(root, 'supabase/migrations')
const tables = new Map()
for (const m of readdirSync(migDir).sort()) {
  const sql = readFileSync(join(migDir, m), 'utf8')
  for (const t of sql.matchAll(/create table (?:if not exists )?(?:public\.)?(\w+)\s*\(([\s\S]*?)\n\);/gi)) {
    const cols = t[2].split('\n').map((l) => l.trim().match(/^(\w+)\s+\w/)?.[1]).filter((c) => c && !/^(constraint|primary|unique|check|foreign)$/i.test(c))
    tables.set(t[1], cols)
  }
  for (const a of sql.matchAll(/alter table (?:if exists )?(?:public\.)?(\w+)([^;]*);/gi))
    for (const c of a[2].matchAll(/add column (?:if not exists )?(\w+)/gi)) tables.get(a[1])?.push(c[1])
  const fns = [...sql.matchAll(/create (?:or replace )?function (?:public\.)?(\w+)/gi)].map((x) => x[1])
  if (fns.length) out.push(`functions in ${m}: ${fns.join(', ')}`)
}
out.push('', '## Tables (migrations; RLS on all)', ...[...tables].map(([t, c]) => `${t}: ${c.join(', ')}`), '',
  'Checks: `npx tsc --noEmit`, `npx eslint src`, `npm run build`, `npm run test:db` (local Supabase on CLEAN).')
console.log(out.join('\n'))
